/**
 * 의료·건강 영역. AI는 자기가 틀렸는지 모른 채 그럴듯하게 답하므로
 * 판단을 맡기지 않고 규칙으로 막는다.
 */
const MEDICAL = /젖몸살|유선염|유방염|멍울|울혈|유두.*(상처|갈라|찢|피)|피가|출혈|열이\s*나|고열|발열|염증|고름|모유량|모유가?\s*(안|적|줄)|단유|끊고|약\s*(먹|복용)|항생제|수유\s*가능한|아기.*(체중|황달|안\s*먹)|산후우울|너무\s*아파|심하게\s*아프/;

/** 사람이 직접 처리해야 하는 사고·불만 */
const ESCALATE = /잘못\s*(왔|보냈|배송|받)|오배송|다른\s*(물건|제품).*왔|파손|깨졌|부서|망가|분실|잃어버렸|도난|환불해|취소해|화가|짜증|어이없|불만|황당|사기/;

export type RiskLevel = "medical" | "escalate" | "none";

export function checkRisk(utterance: string): RiskLevel {
  if (MEDICAL.test(utterance)) return "medical";
  if (ESCALATE.test(utterance)) return "escalate";
  return "none";
}

