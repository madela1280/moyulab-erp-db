/** 평일 09:00~18:00 (KST). 점심시간은 별도로 막지 않는다. */
export function isBusinessHours(now: Date = new Date()): boolean {
  const kst = new Date(now.toLocaleString("en-US", { timeZone: "Asia/Seoul" }));
  const day = kst.getDay();
  const hour = kst.getHours();
  if (day === 0 || day === 6) return false;
  return hour >= 9 && hour < 18;
}

export function agentHoursNote(now: Date = new Date()): string {
  return isBusinessHours(now)
    ? ""
    : "\n\n※ 상담원 연결은 평일 09:00~18:00에 가능합니다.";
}

